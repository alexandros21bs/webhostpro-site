const greekToEnglish = Object.fromEntries(
	Object.entries(englishToGreek)
		.filter(([en]) => !/[\u0370-\u03FF]/.test(en))
		.map(([en, el]) => [el, en])
);

function applyLanguage(lang) {
	const dictionary = lang === "el" ? englishToGreek : greekToEnglish;
	const leaves = document.querySelectorAll("h1, h2, h3, p, a, span, label span, button, option, input, textarea");

	leaves.forEach((node) => {
		if (node.closest(".nav-lang")) {
			return;
		}

		if (node.children.length > 0) {
			return;
		}

		const raw = node.textContent || node.placeholder;
		const key = raw.trim();
		if (!key || !dictionary[key]) {
			return;
		}

		if (node.placeholder && dictionary[key]) {
			node.placeholder = dictionary[key];
			return;
		}

		node.textContent = raw.replace(key, dictionary[key]);
	});

	// Handle copyright line while preserving year and brand.
	const copyNode = document.querySelector(".footer-copy");
	if (copyNode && lang === "el") {
		copyNode.textContent = "© 2026 Web Host Pro. Με επιφύλαξη παντός δικαιώματος.";
	}
	if (copyNode && lang === "en") {
		copyNode.textContent = "© 2026 Web Host Pro. All rights reserved.";
	}

	document.documentElement.lang = lang;
	localStorage.setItem("whp_lang", lang);
}

function setupContactModal() {
	const modal = document.getElementById("contact-modal");
	if (!modal) {
		return;
	}

	const title = modal.querySelector("#contact-modal-title");
	const closeButton = modal.querySelector(".modal-close");
	const openButtons = document.querySelectorAll(".open-contact-modal");

	function openModal(button) {
		const lang = document.documentElement.lang === "el" ? "el" : "en";
		const nextTitle =
			lang === "el"
				? button.getAttribute("data-modal-title-el")
				: button.getAttribute("data-modal-title-en");

		if (title && nextTitle) {
			title.textContent = nextTitle;
		}

		modal.classList.add("is-open");
		modal.setAttribute("aria-hidden", "false");
		document.body.style.overflow = "hidden";
	}

	function closeModal() {
		modal.classList.remove("is-open");
		modal.setAttribute("aria-hidden", "true");
		document.body.style.overflow = "";
	}

	openButtons.forEach((button) => {
		button.addEventListener("click", () => openModal(button));
	});

	if (closeButton) {
		closeButton.addEventListener("click", closeModal);
	}

	modal.addEventListener("click", (event) => {
		if (event.target === modal) {
			closeModal();
		}
	});

	document.addEventListener("keydown", (event) => {
		if (event.key === "Escape" && modal.classList.contains("is-open")) {
			closeModal();
		}
	});
}

document.addEventListener("DOMContentLoaded", () => {
	const langLinks = document.querySelectorAll(".lang-link[data-lang]");
	const savedLang = localStorage.getItem("whp_lang");
	const initialLang = savedLang === "el" || savedLang === "en" ? savedLang : "en";

	langLinks.forEach((item) => item.classList.remove("is-active"));
	const initialLink = document.querySelector(`.lang-link[data-lang="${initialLang}"]`);
	if (initialLink) {
		initialLink.classList.add("is-active");
	}
	setupContactModal();
	applyLanguage(initialLang);

	langLinks.forEach((link) => {
		link.addEventListener("click", (event) => {
			event.preventDefault();
			const lang = link.getAttribute("data-lang") || "en";

			langLinks.forEach((item) => item.classList.remove("is-active"));
			link.classList.add("is-active");
			applyLanguage(lang);
		});
	});
});
